def session_rows(events: list[ScheduleEvent]) -> dict[str, list[ScheduleEvent]]:
    grouped: dict[str, list[ScheduleEvent]] = defaultdict(list)
    for event in events:
        grouped[event.synthetic_session_id].append(event)
    return grouped


def schedule_hourly_stats(events: list[ScheduleEvent], reference_start: datetime, charger_id: str | None = None) -> dict[int, dict[str, float]]:
    grouped_sessions = session_rows(events)
    by_hour: dict[int, list[dict[str, float]]] = defaultdict(list)

    for rows in grouped_sessions.values():
        first = rows[0]
        if charger_id is not None and str(first.charger_id) != str(charger_id):
            continue
        start_hour = (reference_start + timedelta(minutes=first.start_delta_minutes)).hour
        total_energy = sum(row.energy_since_last_event_kwh for row in rows)
        duration_h = (first.end_delta_minutes - first.start_delta_minutes) / 60.0
        by_hour[start_hour].append({"energy": total_energy, "duration": duration_h})

    stats = {}
    for hour, values in by_hour.items():
        stats[hour] = {
            "mean_energy_kwh": sum(v["energy"] for v in values) / len(values),
            "mean_duration_hours": sum(v["duration"] for v in values) / len(values),
            "sample_count": len(values),
        }
    return stats


def first_float(row: dict[str, Any], keys: list[str]) -> float | None:
    for key in keys:
        if key in row and row[key] is not None:
            try:
                return float(row[key])
            except Exception:
                return None
    return None


def normalise_latest_forecast(body: Any) -> list[dict[str, Any]]:
    if isinstance(body, list):
        raw_rows = body
    elif isinstance(body, dict):
        raw_rows = []
        for key in ("items", "data", "results", "forecast", "forecasts", "rows"):
            if isinstance(body.get(key), list):
                raw_rows = body[key]
                break
        if not raw_rows:
            raw_rows = [body]
    else:
        raw_rows = []

    normalised: list[dict[str, Any]] = []
    for row in raw_rows:
        if not isinstance(row, dict):
            continue
        hour = row.get("local_hour", row.get("hour", row.get("starting_hour")))
        if hour is None:
            ts = row.get("timestamp") or row.get("start_time") or row.get("datetime")
            if ts:
                try:
                    hour = datetime.fromisoformat(str(ts).replace("Z", "+00:00")).hour
                except Exception:
                    hour = None
        try:
            hour = int(hour) if hour is not None else None
        except Exception:
            hour = None
        if hour is None:
            continue

        normalised.append({
            "hour": hour,
            "source": row.get("source", row.get("forecast_source", "charger")),
            "mean_energy_kwh": first_float(row, ["mean_energy_kwh", "energy_kWh", "energy_kwh", "mean_energy", "energy"]),
            "mean_duration_hours": first_float(row, ["mean_duration_hours", "duration_hours", "mean_duration", "duration"]),
            "raw": row,
        })
    return normalised


def validate_latest_forecast(client: EVClient, latest_body: Any, events: list[ScheduleEvent], reference_start: datetime, reference_charger_id: str) -> None:
    charger_stats = schedule_hourly_stats(events, reference_start, charger_id=reference_charger_id)
    global_stats = schedule_hourly_stats(events, reference_start, charger_id=None)
    rows = normalise_latest_forecast(latest_body)

    if not rows:
        client.logger.warning("Could not normalise latest forecast response; skipping detailed comparison", response=latest_body)
        return

    for row in rows:
        hour = row["hour"]
        source = str(row.get("source") or "charger").lower()
        expected = global_stats.get(hour) if source == "generic" else charger_stats.get(hour)
        reference = charger_stats.get(hour)
        global_hour = global_stats.get(hour)

        if expected is None:
            client.logger.warning(
                "No schedule-derived statistics for forecast hour",
                hour=hour,
                source=source,
                api_row=row["raw"],
                expected_reference_value=reference,
                expected_global_value=global_hour,
            )
            continue

        for metric in ("mean_energy_kwh", "mean_duration_hours"):
            api_value = row.get(metric)
            expected_value = expected.get(metric)
            if api_value is None or expected_value is None:
                client.logger.warning("Missing forecast metric", hour=hour, source=source, metric=metric, api_row=row["raw"])
                continue
            difference = api_value - expected_value
            passed = math.isclose(api_value, expected_value, abs_tol=FORECAST_COMPARISON_ABS_TOLERANCE)
            client.logger.check(
                f"latest_forecast_{metric}",
                passed=passed,
                hour=hour,
                source=source,
                metric=metric,
                api_value=api_value,
                expected_reference_value=reference.get(metric) if reference else None,
                expected_global_value=global_hour.get(metric) if global_hour else None,
                selected_expected_value=expected_value,
                difference=difference,
                validation_status="pass" if passed else "difference_exceeds_tolerance",
            )


