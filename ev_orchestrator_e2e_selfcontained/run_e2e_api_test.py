def parse_response_body(response: requests.Response) -> Any:
    try:
        return response.json()
    except Exception:
        return response.text


class EVClient:
    def __init__(self, base_url: str, logger: StructuredLogger, username: str | None = None, password: str | None = None):
        self.base_url = base_url.rstrip("/")
        self.logger = logger
        self.username = username
        self.password = password
        self.token: str | None = None
        self.owner_id: str | None = None

    @property
    def auth_headers(self) -> dict[str, str]:
        return {"Authorization": f"Bearer {self.token}"} if self.token else {}

    def login(self, username: str | None = None, password: str | None = None) -> dict[str, Any]:
        if username is not None:
            self.username = username
        if password is not None:
            self.password = password
        if not self.username or not self.password:
            raise RuntimeError("Missing username/password for login.")

        body = self.request(
            "POST",
            "/auth/login",
            json_payload={"user": self.username, "password": self.password},
            auth=False,
            label=f"login {self.username}",
            retry_on_401=False,
        )
        if not isinstance(body, dict) or "access_token" not in body:
            raise RuntimeError(f"Login did not return an access_token. Response: {body}")
        self.token = str(body["access_token"])
        self.owner_id = str(body.get("owner_id")) if body.get("owner_id") is not None else None
        self.logger.info("Logged in", username=self.username, owner_id=self.owner_id)
        return body

    def logout(self) -> None:
        if not self.token:
            return
        try:
            self.try_request("POST", "/auth/logout", label=f"logout {self.username}", retry_on_401=False)
        finally:
            self.token = None
            self.owner_id = None
            self.logger.info("Local token cleared", username=self.username)

    def request(
        self,
        method: str,
        path: str,
        *,
        json_payload: Any | None = None,
        params: dict[str, Any] | None = None,
        auth: bool = True,
        label: str = "",
        retry_on_401: bool = True,
    ) -> Any:
        url = f"{self.base_url}{path}"
        payload_for_log = json_payload if json_payload is not None else params
        response: requests.Response | None = None
        body: Any = None

        response = requests.request(
            method,
            url,
            headers=self.auth_headers if auth else {},
            json=json_payload,
            params=params,
            timeout=HTTP_TIMEOUT_SECONDS,
        )
        body = parse_response_body(response)
        self.logger.http(method, url, payload_for_log, response, body, label)

        if response.status_code == 401 and auth and retry_on_401 and self.username and self.password:
            self.logger.warning("401 received; token may have expired. Re-authenticating and retrying once.", path=path)
            self.login(self.username, self.password)
            response = requests.request(
                method,
                url,
                headers=self.auth_headers,
                json=json_payload,
                params=params,
                timeout=HTTP_TIMEOUT_SECONDS,
            )
            body = parse_response_body(response)
            self.logger.http(method, url, payload_for_log, response, body, label, retry=True)

        response.raise_for_status()
        return body

    def try_request(
        self,
        method: str,
        path: str,
        *,
        json_payload: Any | None = None,
        params: dict[str, Any] | None = None,
        auth: bool = True,
        label: str = "",
        retry_on_401: bool = True,
    ) -> tuple[bool, Any]:
        try:
            body = self.request(
                method,
                path,
                json_payload=json_payload,
                params=params,
                auth=auth,
                label=label,
                retry_on_401=retry_on_401,
            )
            return True, body
        except Exception as exc:
            self.logger.warning("Non-fatal request failed", method=method, path=path, label=label, error=str(exc))
            return False, str(exc)


