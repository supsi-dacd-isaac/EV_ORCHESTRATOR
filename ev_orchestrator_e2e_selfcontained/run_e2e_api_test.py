def get_or_create_chargers(client: EVClient, owner_id: str, pilot_id: str) -> list[Charger]:
    chargers_body = as_list(client.request("GET", "/db/chargers", label="list chargers before creation/reuse"))
    existing_by_name = {row.get("name"): row for row in chargers_body if isinstance(row, dict)}

    chargers: list[Charger] = []
    for index in range(1, CHARGER_COUNT + 1):
        name = charger_name(index)
        existing = existing_by_name.get(name)
        if existing:
            cid = get_id(existing)
            if not cid:
                raise RuntimeError(f"Existing charger has no ID: {existing}")
            nominal = float(existing.get("nominal_power", existing.get("nominal_power_kw", NOMINAL_POWER_KW)))
            chargers.append(Charger(id=cid, name=name, nominal_power_kw=nominal))
            client.logger.info("Reusing existing charger", charger=name, charger_id=cid)
            continue

        payload = {
            "name": name,
            "type": CHARGER_TYPE,
            "latitude": round(BASE_LATITUDE + index * 0.004, 3),
            "longitude": round(BASE_LONGITUDE + index * 0.004, 3),
            "nominal_power": NOMINAL_POWER_KW,
            "plugs": PLUGS,
            "id_owner": owner_id,
            "id_pilot": pilot_id,
        }
        ok, body = client.try_request("POST", "/db/chargers", json_payload=payload, label=f"create charger {name}")
        if ok and isinstance(body, dict):
            cid = get_id(body)
            if not cid:
                raise RuntimeError(f"Created charger response has no ID: {body}")
            chargers.append(Charger(id=cid, name=name, nominal_power_kw=NOMINAL_POWER_KW))
            continue

        # Fallback after duplicate or permission-like issue.
        chargers_body = as_list(client.request("GET", "/db/chargers", label="list chargers after charger-create fallback"))
        existing = find_by_name(chargers_body, name)
        if existing:
            cid = get_id(existing)
            if not cid:
                raise RuntimeError(f"Existing charger has no ID: {existing}")
            nominal = float(existing.get("nominal_power", existing.get("nominal_power_kw", NOMINAL_POWER_KW)))
            chargers.append(Charger(id=cid, name=name, nominal_power_kw=nominal))
            continue
        raise RuntimeError(f"Could not create or find charger {name}. Last response: {body}")

    return chargers


def inject_charger_ids(events: list[ScheduleEvent], chargers: list[Charger]) -> None:
    by_name = {charger.name: charger for charger in chargers}
    for event in events:
        charger = by_name.get(event.charger_name)
        if not charger:
            raise RuntimeError(f"Schedule references unknown charger name: {event.charger_name}")
        event.charger_id = charger.id


