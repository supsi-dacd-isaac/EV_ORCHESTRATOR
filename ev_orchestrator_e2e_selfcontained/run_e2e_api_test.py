def now_utc_iso() -> str:
    return datetime.utcnow().replace(microsecond=0).isoformat() + "Z"


def redact(value: Any) -> Any:
    sensitive_keys = {"password", "token", "access_token", "authorization"}
    if isinstance(value, dict):
        return {k: "***REDACTED***" if str(k).lower() in sensitive_keys else redact(v) for k, v in value.items()}
    if isinstance(value, list):
        return [redact(v) for v in value]
    if isinstance(value, tuple):
        return tuple(redact(v) for v in value)
    if isinstance(value, datetime):
        return value.isoformat()
    return value


class StructuredLogger:
    def __init__(self, output_dir: Path, run_id: str):
        output_dir.mkdir(parents=True, exist_ok=True)
        self.human_log_path = output_dir / f"{RUN_LOG_PREFIX}_{run_id}.log"
        self.jsonl_log_path = output_dir / f"{RUN_LOG_PREFIX}_{run_id}.jsonl"

        self.logger = logging.getLogger(f"{RUN_LOG_PREFIX}_{run_id}")
        self.logger.setLevel(logging.INFO)
        self.logger.handlers.clear()

        fmt = logging.Formatter("%(asctime)s | %(levelname)s | %(message)s")
        file_handler = logging.FileHandler(self.human_log_path, encoding="utf-8")
        file_handler.setFormatter(fmt)
        self.logger.addHandler(file_handler)

        console_handler = logging.StreamHandler(sys.stdout)
        console_handler.setFormatter(fmt)
        self.logger.addHandler(console_handler)

    def info(self, message: str, **data: Any) -> None:
        self._write("INFO", message, data)

    def warning(self, message: str, **data: Any) -> None:
        self._write("WARNING", message, data)

    def error(self, message: str, **data: Any) -> None:
        self._write("ERROR", message, data)

    def check(self, name: str, passed: bool, **data: Any) -> None:
        self._write("INFO" if passed else "WARNING", f"CHECK {name}: {'PASS' if passed else 'FAIL'}", {
            "check": name,
            "passed": passed,
            **data,
        })

    def http(self, method: str, url: str, payload: Any, response: requests.Response | None, body: Any, label: str, retry: bool = False) -> None:
        status_code = response.status_code if response is not None else None
        ok = bool(response.ok) if response is not None else False
        self._write("INFO" if ok else "WARNING", f"HTTP {method} {url} -> {status_code} | {label}", {
            "event": "http_request",
            "label": label,
            "method": method,
            "url": url,
            "request_payload": redact(payload),
            "status_code": status_code,
            "ok": ok,
            "response_body": redact(body),
            "retry": retry,
        })

    def _write(self, level: str, message: str, data: dict[str, Any]) -> None:
        record = {
            "ts_utc": now_utc_iso(),
            "level": level,
            "message": message,
            **redact(data),
        }
        with self.jsonl_log_path.open("a", encoding="utf-8") as f:
            f.write(json.dumps(record, ensure_ascii=False, default=str) + "\n")

        suffix = " | " + json.dumps(redact(data), ensure_ascii=False, default=str) if data else ""
        if level == "ERROR":
            self.logger.error(message + suffix)
        elif level == "WARNING":
            self.logger.warning(message + suffix)
        else:
            self.logger.info(message + suffix)


