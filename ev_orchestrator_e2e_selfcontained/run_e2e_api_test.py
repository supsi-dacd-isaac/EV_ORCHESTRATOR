def parse_bool(value: Any) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in {"true", "1", "yes", "y"}


def parse_event(row: dict[str, str]) -> ScheduleEvent:
    return ScheduleEvent(
        row_id=int(row["row_id"]),
        synthetic_session_id=row["synthetic_session_id"],
        day_index=int(row["day_index"]),
        charger_index=int(row["charger_index"]),
        charger_name=row["charger_name"],
        charger_id=row.get("charger_id", ""),
        event_type=row["event_type"],
        timestamp_delta_minutes=int(float(row["timestamp_delta_minutes"])),
        start_delta_minutes=int(float(row["start_delta_minutes"])),
        end_delta_minutes=int(float(row["end_delta_minutes"])),
        end_charging_delta_minutes=int(float(row["end_charging_delta_minutes"])),
        charging_rate_kw=float(row["charging_rate_kw"]),
        energy_since_last_event_kwh=float(row["energy_since_last_event_kwh"]),
        cumulative_energy_kwh=float(row["cumulative_energy_kwh"]),
        fully_charged=parse_bool(row["fully_charged"]),
        action=int(float(row["action"])),
        nominal_power_kw=float(row["nominal_power_kw"]),
        target_energy_kwh=float(row["target_energy_kwh"]),
        expected_duration_minutes=int(float(row["expected_duration_minutes"])),
    )


def load_schedule(path: Path) -> list[ScheduleEvent]:
    if not path.exists():
        raise FileNotFoundError(
            f"Schedule CSV not found: {path}. Run generate_charging_schedule.py first."
        )
    with path.open("r", newline="", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        events = [parse_event(row) for row in reader]
    events.sort(key=lambda event: (event.timestamp_delta_minutes, event.row_id))
    return events


def write_resolved_schedule(path: Path, events: list[ScheduleEvent], reference_start: datetime) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    rows = []
    for event in events:
        row = asdict(event)
        row["timestamp_abs"] = timestamp_from_delta(reference_start, event.timestamp_delta_minutes)
        row["start_abs"] = timestamp_from_delta(reference_start, event.start_delta_minutes)
        row["end_abs"] = timestamp_from_delta(reference_start, event.end_delta_minutes)
        row["end_charging_abs"] = timestamp_from_delta(reference_start, event.end_charging_delta_minutes)
        rows.append(row)
    with path.open("w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def timestamp_from_delta(reference_start: datetime, delta_minutes: int) -> str:
    return (reference_start + timedelta(minutes=delta_minutes)).isoformat()


