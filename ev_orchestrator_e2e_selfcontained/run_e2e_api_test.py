def as_list(body: Any) -> list[Any]:
    if isinstance(body, list):
        return body
    if isinstance(body, dict):
        for key in ("items", "data", "results", "owners", "pilots", "chargers"):
            if isinstance(body.get(key), list):
                return body[key]
    return []


def get_id(obj: dict[str, Any]) -> str | None:
    for key in ("id", "owner_id", "id_owner", "pilot_id", "id_pilot", "charger_id", "id_charger"):
        if obj.get(key) is not None:
            return str(obj[key])
    return None


def find_by_user(rows: Iterable[Any], user: str) -> dict[str, Any] | None:
    for row in rows:
        if isinstance(row, dict) and row.get("user") == user:
            return row
    return None


def find_by_name(rows: Iterable[Any], name: str) -> dict[str, Any] | None:
    for row in rows:
        if isinstance(row, dict) and row.get("name") == name:
            return row
    return None


