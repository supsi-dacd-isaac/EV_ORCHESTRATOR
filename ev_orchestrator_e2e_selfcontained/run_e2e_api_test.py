def event_payload(event: ScheduleEvent, reference_start: datetime) -> dict[str, Any]:
    timestamp = timestamp_from_delta(reference_start, event.timestamp_delta_minutes)
    if event.event_type == "vehicle_connected":
        return {
            "charger_id": event.charger_id,
            "timestamp": timestamp,
            "measured_power_kw": event.charging_rate_kw,
            "is_fully_charged": event.fully_charged,
        }
    if event.event_type == "charging_update":
        return {
            "charger_id": event.charger_id,
            "timestamp": timestamp,
            "avg_power_last_15min_kw": event.charging_rate_kw,
            "energy_delivered_kwh": event.energy_since_last_event_kwh,
            "is_fully_charged": event.fully_charged,
        }
    if event.event_type == "vehicle_disconnected":
        return {
            "charger_id": event.charger_id,
            "timestamp": timestamp,
            "avg_power_last_15min_kw": event.charging_rate_kw,
            "energy_delivered_kwh": event.energy_since_last_event_kwh,
            "is_fully_charged": event.fully_charged,
        }
    raise ValueError(f"Unsupported event_type: {event.event_type}")


def extract_session_id(body: Any) -> str | None:
    if isinstance(body, dict):
        for key in ("session_id", "id_session", "id", "sessionId"):
            if body.get(key) is not None:
                return str(body[key])
        for value in body.values():
            found = extract_session_id(value)
            if found:
                return found
    if isinstance(body, list):
        for item in body:
            found = extract_session_id(item)
            if found:
                return found
    return None


def active_count_from_body(body: Any) -> int | None:
    if isinstance(body, dict):
        for key in ("count", "active_count", "n_active", "total"):
            if key in body:
                try:
                    return int(body[key])
                except Exception:
                    pass
        for key in ("items", "data", "results", "sessions", "active_sessions"):
            if isinstance(body.get(key), list):
                return len(body[key])
        # In the debug script, active sessions are treated as a dict keyed by session ID.
        return len(body)
    if isinstance(body, list):
        return len(body)
    return None


def resolve_session_id_from_active_sessions(body: Any, charger_id: str) -> str | None:
    if isinstance(body, dict):
        for possible_session_id, value in body.items():
            if isinstance(value, dict):
                if str(value.get("charger_id") or value.get("id_charger") or "") == str(charger_id):
                    return str(possible_session_id)
                found = extract_session_id(value)
                if found and str(value.get("charger_id") or value.get("id_charger") or "") == str(charger_id):
                    return found
        for key in ("items", "data", "results", "sessions", "active_sessions"):
            if isinstance(body.get(key), list):
                return resolve_session_id_from_active_sessions(body[key], charger_id)
    elif isinstance(body, list):
        for row in body:
            if isinstance(row, dict) and str(row.get("charger_id") or row.get("id_charger") or "") == str(charger_id):
                return extract_session_id(row)
    return None


def active_validation_deltas() -> list[int]:
    step = int(24 * 60 / ACTIVE_SESSION_CHECKS_PER_DAY)
    deltas: list[int] = []
    for day in range(SCHEDULE_DAYS):
        day_offset = day * 24 * 60
        for i in range(ACTIVE_SESSION_CHECKS_PER_DAY):
            # Add 15 minutes to avoid checking exactly at midnight / boundary points.
            deltas.append(day_offset + i * step + 15)
    return deltas


def expected_active_session_ids(events: list[ScheduleEvent], delta_minutes: int) -> list[str]:
    by_session: dict[str, tuple[int, int]] = {}
    for event in events:
        by_session[event.synthetic_session_id] = (event.start_delta_minutes, event.end_delta_minutes)
    return [session_id for session_id, (start, end) in by_session.items() if start <= delta_minutes < end]


def sleep_until_next_delta(previous_delta: int, next_delta: int, logger: StructuredLogger) -> None:
    if not USE_SLEEP_BETWEEN_SCHEDULED_CALLS:
        return
    delta = max(0, next_delta - previous_delta)
    sleep_seconds = delta * 60.0 / TIME_SCALE
    if sleep_seconds > 0:
        logger.info("Sleeping before next scheduled API call", simulated_delta_minutes=delta, sleep_seconds=round(sleep_seconds, 3))
        time.sleep(sleep_seconds)


def execute_schedule(client: EVClient, events: list[ScheduleEvent], reference_start: datetime) -> str | None:
    events_by_delta: dict[int, list[ScheduleEvent]] = defaultdict(list)
    for event in events:
        events_by_delta[event.timestamp_delta_minutes].append(event)

    checkpoints = set(active_validation_deltas())
    timeline = sorted(set(events_by_delta.keys()) | checkpoints)
    previous_delta = 0
    known_api_session_ids: dict[str, str] = {}
    last_synthetic_session_id = events[-1].synthetic_session_id if events else None
    last_api_session_id: str | None = None

    for delta in timeline:
        sleep_until_next_delta(previous_delta, delta, client.logger)
        previous_delta = delta

        for event in events_by_delta.get(delta, []):
            if event.event_type == "vehicle_disconnected":
                # Try to capture API session ID just before closing the session.
                ok, active_body = client.try_request("GET", "/events/active_sessions", label="active sessions before disconnect")
                if ok:
                    sid = resolve_session_id_from_active_sessions(active_body, event.charger_id)
                    if sid:
                        known_api_session_ids[event.synthetic_session_id] = sid
                        if event.synthetic_session_id == last_synthetic_session_id:
                            last_api_session_id = sid

            path = f"/events/{event.event_type}"
            payload = event_payload(event, reference_start)
            ok, body = client.try_request("POST", path, json_payload=payload, label=f"{event.event_type} {event.synthetic_session_id}")
            if not ok:
                client.logger.warning("Charging event failed", event=asdict(event), response=body)
                continue

            sid = extract_session_id(body)
            if sid:
                known_api_session_ids[event.synthetic_session_id] = sid
                if event.synthetic_session_id == last_synthetic_session_id:
                    last_api_session_id = sid

        if delta in checkpoints:
            expected_ids = expected_active_session_ids(events, delta)
            ok, active_body = client.try_request("GET", "/events/active_sessions", label="scheduled active-session validation")
            actual_count = active_count_from_body(active_body) if ok else None
            client.logger.check(
                "active_sessions_count",
                passed=ok and actual_count == len(expected_ids),
                timestamp_delta_minutes=delta,
                timestamp_abs=timestamp_from_delta(reference_start, delta),
                expected_active_sessions=len(expected_ids),
                actual_active_sessions=actual_count,
                expected_synthetic_session_ids=expected_ids,
                details=active_body,
            )

    if last_api_session_id is None and last_synthetic_session_id is not None:
        last_api_session_id = known_api_session_ids.get(last_synthetic_session_id)
    return last_api_session_id


