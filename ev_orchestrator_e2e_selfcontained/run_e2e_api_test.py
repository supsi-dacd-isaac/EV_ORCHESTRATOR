def main() -> None:
    verify_admin_credentials_are_not_placeholders()

    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    tz = ZoneInfo(TIMEZONE)
    run_id = datetime.now(tz).strftime("%Y%m%d_%H%M%S")
    logger = StructuredLogger(OUTPUT_DIR, run_id)

    logger.info("Starting EV Orchestrator E2E API test", base_url=BASE_URL, schedule_csv=str(SCHEDULE_CSV_PATH), run_id=run_id)

    # 0. Health check / reachability.
    public_client = EVClient(BASE_URL, logger)
    ok, health_body = public_client.try_request("GET", "/health", auth=False, label="health check /health")
    if not ok:
        ok_docs, docs_body = public_client.try_request("GET", "/docs", auth=False, label="fallback reachability check /docs")
        logger.check("service_reachable", passed=ok_docs, health_response=health_body, docs_response=docs_body)
    else:
        logger.check("service_reachable", passed=True, health_response=health_body)

    # Load and check CSV before writing anything to the API.
    events = load_schedule(SCHEDULE_CSV_PATH)
    validate_schedule_file(events, logger)

    # 1. Login as admin.
    admin = EVClient(BASE_URL, logger, ADMIN_USERNAME, ADMIN_PASSWORD)
    admin.login()

    # 2. Create/reuse user.
    owner = get_or_create_owner(admin)
    owner_id = get_id(owner)
    if not owner_id:
        raise RuntimeError(f"Cannot determine owner id for {TEST_USERNAME}: {owner}")

    # 3. Create/reuse pilot.
    pilot = get_or_create_pilot(admin, owner_id)
    pilot_id = get_id(pilot)
    if not pilot_id:
        raise RuntimeError(f"Cannot determine pilot id for {PILOT_NAME}: {pilot}")

    # 4. Logout admin.
    admin.logout()

    # 5. Login as interped_user1.
    user_client = EVClient(BASE_URL, logger, TEST_USERNAME, TEST_PASSWORD)
    user_client.login()

    # 6. Check existing pilots.
    pilots = as_list(user_client.request("GET", "/db/pilots", label="list pilots as interped_user1"))
    pilot_visible = find_by_name(pilots, PILOT_NAME) is not None
    logger.check("pilot_visible_to_interped_user1", passed=pilot_visible, pilot_name=PILOT_NAME)

    # 7. Create/reuse chargers. If user permissions do not allow this, retry as admin.
    try:
        chargers = get_or_create_chargers(user_client, owner_id, pilot_id)
    except Exception as exc:
        logger.warning("Charger setup as interped_user1 failed; retrying as admin", error=str(exc))
        user_client.logout()
        admin = EVClient(BASE_URL, logger, ADMIN_USERNAME, ADMIN_PASSWORD)
        admin.login()
        chargers = get_or_create_chargers(admin, owner_id, pilot_id)
        admin.logout()
        user_client.login()

    if len(chargers) != CHARGER_COUNT:
        raise RuntimeError(f"Expected {CHARGER_COUNT} chargers; got {len(chargers)}")

    # Resolve charger IDs into the schedule and log the runtime reference start.
    inject_charger_ids(events, chargers)
    reference_start = datetime.now(tz).replace(second=0, microsecond=0) + timedelta(minutes=START_DELAY_MINUTES)
    resolved_schedule_path = OUTPUT_DIR / f"{RESOLVED_SCHEDULE_PREFIX}_{run_id}.csv"
    write_resolved_schedule(resolved_schedule_path, events, reference_start)
    logger.info(
        "Resolved schedule and reference start",
        reference_start=reference_start.isoformat(),
        resolved_schedule_csv=str(resolved_schedule_path),
        time_scale=TIME_SCALE,
        use_sleep_between_scheduled_calls=USE_SLEEP_BETWEEN_SCHEDULED_CALLS,
    )

    if DRY_RUN_AFTER_SETUP:
        logger.warning("DRY_RUN_AFTER_SETUP is True; stopping before session event execution")
        user_client.logout()
        print_output_summary(logger, resolved_schedule_path)
        return

    # 8 and 9. Execute synthetic schedule and validate active sessions 4 times/day.
    last_api_session_id = execute_schedule(user_client, events, reference_start)

    # Additional one-off endpoint checks.
    for path in ("/db/owners", "/db/pilots", "/db/chargers"):
        user_client.try_request("GET", path, label=f"one-off endpoint check {path}")

    # 10. Charger history for one charger.
    history_charger = chargers[0]
    user_client.try_request("GET", f"/forecaster/charger/{history_charger.id}/history", label=f"charger history {history_charger.name}")

    # 11. Latest charger forecast for another charger + comparison.
    latest_charger = chargers[1]
    ok, latest_body = user_client.try_request("GET", f"/forecaster/charger/{latest_charger.id}/latest", label=f"charger latest {latest_charger.name}")
    if ok:
        validate_latest_forecast(user_client, latest_body, events, reference_start, reference_charger_id=latest_charger.id)

    # 12. Actions for last session.
    if last_api_session_id:
        ok, actions_body = user_client.try_request("GET", f"/sessions/actions/session/{last_api_session_id}", label="last session actions")
        if ok:
            print("\n/sessions/actions/session/{session_id} response for the last session:")
            print(json.dumps(actions_body, indent=2, default=str))
    else:
        logger.warning("Could not determine API session ID for the last synthetic session; skipping session actions endpoint")

    # 13. Forecast jobs.
    ok, forecast_jobs_body = user_client.try_request("GET", "/db/forecast_jobs", label="list forecast jobs")
    if ok:
        print("\n/db/forecast_jobs response:")
        print(json.dumps(forecast_jobs_body, indent=2, default=str))

    # 14. Logout.
    user_client.logout()

    logger.info("Completed EV Orchestrator E2E API test")
    print_output_summary(logger, resolved_schedule_path)


def print_output_summary(logger: StructuredLogger, resolved_schedule_path: Path) -> None:
    print("\nGenerated / updated files:")
    print(f"  human log:          {logger.human_log_path}")
    print(f"  structured JSONL:   {logger.jsonl_log_path}")
    print(f"  resolved schedule:  {resolved_schedule_path}")


