def validate_schedule_file(events: list[ScheduleEvent], logger: StructuredLogger) -> None:
    if not events:
        raise RuntimeError("The schedule CSV contains no events.")

    zero_bad = [e for e in events if e.action == 0 and (e.energy_since_last_event_kwh != 0 or e.charging_rate_kw != 0)]
    logger.check(
        "action_zero_has_zero_power_and_energy",
        passed=len(zero_bad) == 0,
        invalid_rows=[e.row_id for e in zero_bad[:20]],
        invalid_count=len(zero_bad),
    )

    too_high_power = [e for e in events if e.charging_rate_kw >= e.nominal_power_kw]
    logger.check(
        "charging_rate_below_nominal_power",
        passed=len(too_high_power) == 0,
        invalid_rows=[e.row_id for e in too_high_power[:20]],
        invalid_count=len(too_high_power),
    )

    zero_not_full_total = 0
    zero_not_full_by_charger: dict[str, int] = defaultdict(int)
    for event in events:
        if event.action == 0 and not event.fully_charged:
            zero_not_full_total += 1
            zero_not_full_by_charger[event.charger_name] += 1
    logger.info(
        "Counted action=0 while vehicle not fully charged",
        total=zero_not_full_total,
        by_charger=dict(zero_not_full_by_charger),
    )


